export function getYSequenceWithoutColon(Y: string): {
	type: string;
	Y: string;
} {
	if (Y.startsWith('Y(')) {
		return { type: '1-Y', Y: Y.slice(2, -1) };
	}
	if (Y.startsWith('ω-Y(')) {
		return { type: 'ω-Y', Y: Y.slice(4, -1) };
	}
	return {
		type: '???',
		Y,
	};
}

